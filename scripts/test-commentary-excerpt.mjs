import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = await readFile(new URL("../src/lib/commentary-excerpt.ts", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } });
const { validateCommentaryExcerpt: validate, COMMENTARY_EXCERPT_LIMIT: limit, findCommentaryMatches: find, commentaryMatchContext: context } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
const original = "Opening context.\nExact words, with punctuation!\nClosing context.";
assert.deepEqual(validate(original, "  Exact words, with punctuation!  "), { text: "Exact words, with punctuation!", start: 17, error: "" });
assert.equal(validate(original, original).error, "");
assert.equal(validate(original, "context.\nExact words").error, "");
assert.notEqual(validate(original, "exact words, with punctuation!").error, "");
assert.notEqual(validate(original, "Opening context. Closing context.").error, "");
assert.notEqual(validate(original, "  ").error, "");
assert.notEqual(validate(original, "A paraphrase").error, "");
assert.equal(validate("x".repeat(limit), "x".repeat(limit)).error, "");
assert.notEqual(validate("x".repeat(limit + 1), "x".repeat(limit + 1)).error, "");
assert.equal(validate("Repeated. Repeated.", "Repeated.").start, 0);
console.log("PASS: 10 exact-excerpt validation checks (wording, context, whitespace, limits, location).");
assert.deepEqual(find("Grace, grace; GRACE.", "grace"), [{ start: 0, end: 5 }, { start: 7, end: 12 }, { start: 14, end: 19 }]);
assert.deepEqual(find("A [word].* + (test)?", "[word].*"), [{ start: 2, end: 10 }]);
assert.deepEqual(find("İ 😀 Grace", "grace"), [{ start: 5, end: 10 }]);
assert.deepEqual(find("Grace", "  "), []);
assert.deepEqual(find("Grace", "missing"), []);
assert.deepEqual(find("Grace", " grace "), [{ start: 0, end: 5 }]);
assert.deepEqual(find("aaaa", "aa"), [{ start: 0, end: 2 }, { start: 2, end: 4 }]);
const longText = "Before ".repeat(90) + "Exact MATCH" + " after".repeat(90);
const window = context(longText, find(longText, "exact match")[0]);
assert.equal(window.before + window.matched + window.after, window.text);
assert.equal(window.matched, "Exact MATCH");
assert.equal(validate(longText, window.text).error, "");
assert.equal(context("Grace", { start: 0, end: 5 }).text, "Grace");
console.log("PASS: 11 source-search checks (literal matching, Unicode offsets, navigation data, exact context).");
