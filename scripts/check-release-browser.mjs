import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base=process.env.RELEASE_TEST_URL || 'http://127.0.0.1:3110';
const output=process.env.RELEASE_TEST_OUTPUT || '/private/tmp/bible-release-browser';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
try {
const context=await browser.newContext({viewport:{width:1024,height:1366}});
const page=await context.newPage();
page.on('dialog', dialog => dialog.accept());
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/#sermons');
await page.getByText('Install app & offline study',{exact:true}).click();
await page.getByRole('button',{name:'Download for offline study',exact:true}).click();
console.log('download requested');
await page.getByText('Offline copy ready: KJV reading and local lesson preparation.',{exact:true}).waitFor({timeout:180000});
const manifest=await page.evaluate(async()=>await(await fetch('/manifest.webmanifest')).json());
assert.equal(manifest.display,'standalone');assert.equal(manifest.icons.length,2);
const count=await page.evaluate(async()=>{
 const all=Object.assign({},...(await Promise.all([1,2,3,4].map(async part=>(await(await fetch('/api/bible?part='+part)).json()).verses))));
 return {total:Object.keys(all).length,corinthians:Object.keys(all).filter(k=>k.startsWith('2 Corinthians ')).length,last:all['2 Corinthians 13:14']};
});
assert.equal(count.total,31102);assert.equal(count.corinthians,257);assert.match(count.last,/The grace of the Lord Jesus Christ/);
console.log('download complete');
await context.setOffline(true);
await page.reload();
await page.getByRole('heading',{name:'Prepare to teach',exact:true}).waitFor();
// A real offline API response must exist before the template is generated.
assert.equal(await page.evaluate(async()=>(await(await fetch('/api/bible?part=4')).json()).verses['2 Corinthians 2:8']), 'Wherefore I beseech you that ye would confirm [your] love toward him.');
console.log('offline reload passed');
await page.getByRole('button',{name:'2 Corinthians 2 lesson',exact:true}).click();
await page.getByRole('heading',{name:'Sunday School teaching plan',exact:true}).waitFor();
await page.getByRole('button',{name:'Save',exact:true}).click();
console.log('lesson saved');
const saved=await page.evaluate(()=>Object.values(localStorage).flatMap(v=>{try{const a=JSON.parse(v);return Array.isArray(a)?a:[]}catch{return []}}).find(x=>x?.lessonPlan&&x.passage==='2 Corinthians 2:1-17'));
assert.ok(saved);assert.ok(saved.slides.some(s=>s.bibleText.includes('2 Corinthians 2:17 ')));assert.equal(saved.targetMinutes,35);
for(const segment of saved.lessonPlan.segments)assert.ok(!saved.slides.some(s=>(s.body+' '+s.bibleText).includes(segment.answer)));
await page.screenshot({path:output+'/offline-lesson-ipad.png'});
await page.clock.install();
await page.getByRole('button',{name:'Teach from notes',exact:true}).click();
await page.getByText('Remaining',{exact:true}).waitFor();
await page.clock.fastForward(11000);
assert.ok((await page.locator('body').innerText()).includes('34:49'));
await page.screenshot({path:output+'/offline-teaching-timer.png'});
await page.getByRole('button',{name:'Back to Builder',exact:true}).click();
await page.getByRole('button',{name:'Pre-class countdown',exact:true}).click();
const dialog=page.getByRole('dialog',{name:'Pre-class countdown builder'});
await dialog.getByLabel('I reviewed the answers',{exact:false}).check();
console.log('countdown opened');
await dialog.getByRole('button',{name:'Save countdown',exact:true}).click();
await dialog.getByRole('button',{name:'Start preview',exact:true}).click();
const before=await dialog.getByRole('timer').innerText();await page.clock.fastForward(11000);
const after=await dialog.getByRole('timer').innerText();assert.notEqual(before,after);
await page.setViewportSize({width:390,height:844});
assert.ok(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth));
await page.screenshot({path:output+'/offline-countdown-iphone.png'});
await dialog.getByRole('button',{name:'Close',exact:true}).click();
await page.getByRole('button',{name:'2 Corinthians 6 lesson',exact:true}).click();
await page.getByRole('button',{name:'Save',exact:true}).click();
const future=await page.evaluate(()=>Object.values(localStorage).flatMap(v=>{try{const a=JSON.parse(v);return Array.isArray(a)?a:[]}catch{return []}}).find(x=>x?.lessonPlan&&x.passage==='2 Corinthians 6:1-18'));
assert.equal(future.lessonPlan.date,'2026-10-11');assert.ok(future.slides.some(s=>s.bibleText.includes('2 Corinthians 6:18 ')));
await page.reload();
assert.ok(await page.evaluate(()=>Object.values(localStorage).some(v=>v.includes('The Ministry of Forgiveness'))));
assert.deepEqual(errors,[]);
console.log('PASS: install metadata, offline hard reload, all 31,102 KJV verses (257 in 2 Corinthians), lesson 2 save and slides, private answers excluded, teaching timer and ticking countdown at iPhone width, October 11 lesson 6, persistence after reload.');
console.log('Screenshots: '+output);
} finally {await browser.close();}
